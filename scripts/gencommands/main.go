// Command gencommands writes docs/commands.md: every command the server
// registers, grouped by family, with its arity, flags and key positions. It
// asks an in-process server (COMMAND and COMMAND DOCS), so the page cannot
// drift from the command table.
//
//	go run ./scripts/gencommands > docs/commands.md
package main

import (
	"bufio"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/rabbicse/distcache/internal/config"
	"github.com/rabbicse/distcache/internal/resp"
	"github.com/rabbicse/distcache/internal/server"
)

// commandInfo is one row of the generated tables.
type commandInfo struct {
	name        string
	arity       int64
	flags       []string
	first, last int64
	step        int64
	subcommands []string
}

// groupTitles orders the families and gives them readable headings. Groups
// the server reports that are missing here are appended alphabetically.
var groupTitles = [][2]string{
	{"string", "Strings"},
	{"bitmap", "Bitmaps"},
	{"list", "Lists"},
	{"hash", "Hashes"},
	{"set", "Sets"},
	{"sortedset", "Sorted sets"},
	{"stream", "Streams"},
	{"hyperloglog", "HyperLogLog"},
	{"geo", "Geospatial"},
	{"keyspace", "Keys and expiry"},
	{"transaction", "Transactions"},
	{"scripting", "Scripting and functions"},
	{"pubsub", "Pub/Sub"},
	{"connection", "Connection"},
	{"server", "Server and administration"},
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gencommands:", err)
		os.Exit(1)
	}
}

func run() error {
	dir, err := os.MkdirTemp("", "gencommands")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(dir) }() // best-effort: temp dir cleanup
	cfg := config.Default()
	cfg.Dir = dir
	cfg.Save = nil
	srv := server.New(cfg, nil)

	infoReply, err := srv.Exec("COMMAND")
	if err != nil {
		return err
	}
	docsReply, err := srv.Exec("COMMAND", "DOCS")
	if err != nil {
		return err
	}
	groups := commandGroups(docsReply)
	byGroup := map[string][]commandInfo{}
	total := 0
	for _, e := range infoReply.Elems {
		ci := parseInfo(e)
		g := groups[ci.name]
		byGroup[g] = append(byGroup[g], ci)
		total++
	}

	out := bufio.NewWriter(os.Stdout)
	defer func() { _ = out.Flush() }() // best-effort: stdout
	fmt.Fprintf(out, "# Command reference\n\n")
	fmt.Fprintf(out, "<!-- Generated by `make docs-commands` (scripts/gencommands). Do not edit by hand. -->\n\n")
	fmt.Fprintf(out, "DistCache %s implements %d commands with the names, arguments and replies of Redis %s. ", server.Version, total, server.RedisVersion)
	fmt.Fprintf(out, "For what each command does, the Redis documentation applies: `https://redis.io/commands/<name>`. ")
	fmt.Fprintf(out, "Commands Redis has and DistCache lacks are listed in [redis-compatibility.md](redis-compatibility.md).\n\n")
	fmt.Fprintf(out, "How to read the tables:\n\n")
	fmt.Fprintf(out, "- **Arity** counts the command name. `3` means exactly three words; `-3` means three or more.\n")
	fmt.Fprintf(out, "- **Keys** is `first, last, step`: the argument positions that hold key names. `-1` as last means \"to the end\". ")
	fmt.Fprintf(out, "`by argument` means the key positions depend on the arguments (a `numkeys` count, for example).\n")
	fmt.Fprintf(out, "- **Flags** are the Redis command flags. `write` commands take write locks on their keys' shards and are written to the AOF and to replicas; ")
	fmt.Fprintf(out, "`readonly` commands take read locks, so they run in parallel even on the same shard.\n\n")

	seen := map[string]bool{}
	printed := map[string]bool{}
	for _, gt := range groupTitles {
		seen[gt[0]] = true
	}
	var extra []string
	for g := range byGroup {
		if !seen[g] {
			extra = append(extra, g)
		}
	}
	sort.Strings(extra)
	order := groupTitles
	for _, g := range extra {
		order = append(order, [2]string{g, g})
	}
	for _, gt := range order {
		cmds := byGroup[gt[0]]
		if len(cmds) == 0 || printed[gt[0]] {
			continue
		}
		printed[gt[0]] = true
		sort.Slice(cmds, func(i, j int) bool { return cmds[i].name < cmds[j].name })
		fmt.Fprintf(out, "## %s (%d)\n\n", gt[1], len(cmds))
		fmt.Fprintf(out, "| Command | Arity | Keys | Flags | Subcommands |\n|---|---:|---|---|---|\n")
		for _, c := range cmds {
			fmt.Fprintf(out, "| `%s` | %d | %s | %s | %s |\n", strings.ToUpper(c.name), c.arity, keySpec(c),
				strings.Join(c.flags, ", "), strings.Join(c.subcommands, ", "))
		}
		fmt.Fprintln(out)
	}
	return nil
}

// keySpec renders a command's key positions for the table.
func keySpec(c commandInfo) string {
	movable := false
	for _, f := range c.flags {
		if f == "movablekeys" {
			movable = true
		}
	}
	switch {
	case c.first == 0 && movable:
		return "by argument"
	case c.first == 0:
		return "none"
	default:
		return fmt.Sprintf("%d, %d, %d", c.first, c.last, c.step)
	}
}

// parseInfo decodes one COMMAND entry: name, arity, flags, first key, last
// key, step, ACL categories, tips, key specs, subcommands.
func parseInfo(e resp.Value) commandInfo {
	ci := commandInfo{name: strings.ToLower(string(e.Elems[0].Str)), arity: e.Elems[1].Int,
		first: e.Elems[3].Int, last: e.Elems[4].Int, step: e.Elems[5].Int}
	for _, f := range e.Elems[2].Elems {
		ci.flags = append(ci.flags, string(f.Str))
	}
	sort.Strings(ci.flags)
	if len(e.Elems) > 9 {
		for _, sub := range e.Elems[9].Elems {
			full := strings.ToUpper(string(sub.Elems[0].Str))
			if _, name, ok := strings.Cut(full, "|"); ok {
				full = name
			}
			ci.subcommands = append(ci.subcommands, full)
		}
		sort.Strings(ci.subcommands)
	}
	return ci
}

// commandGroups maps each command name to its group from COMMAND DOCS, whose
// reply alternates a name with a flat field/value list.
func commandGroups(docs resp.Value) map[string]string {
	groups := map[string]string{}
	for i := 0; i+1 < len(docs.Elems); i += 2 {
		name := strings.ToLower(string(docs.Elems[i].Str))
		fields := docs.Elems[i+1].Elems
		for j := 0; j+1 < len(fields); j += 2 {
			if string(fields[j].Str) == "group" {
				groups[name] = string(fields[j+1].Str)
			}
		}
	}
	return groups
}
